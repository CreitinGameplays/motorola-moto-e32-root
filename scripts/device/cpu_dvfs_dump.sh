#!/system/bin/sh
# Dump the CPU DVFS register state (all always-on blocks, safe any time).
#   base 2 = apcpu dvfs (0x64018000): cluster map tables + work indexes
#   base 3 = glbregs 0x645a0000: mpll-ananke/scu slot registers
#   base 4 = glbregs 0x64580000: mpll-prometheus slot registers

P=/sys/kernel/gpu_gpll_poker
OUT=/data/local/tmp/cpu_dvfs_regs.txt
DF=/sys/devices/system/cpu/cpufreq/cpudvfs

log() { echo "$1" >> $OUT; }

rdb() {	# rdb <base> <off>
	echo $1 > $P/base
	echo "$2" > $P/rd
	log "$(cat $P/rd)"
}

echo "--- $(date)" > $OUT

log "== cpufreq tables =="
for c in 0 6; do
	log "cpu$c freqs: $(cat /sys/devices/system/cpu/cpu$c/cpufreq/scaling_available_frequencies 2>/dev/null)"
	log "cpu$c cur: $(cat /sys/devices/system/cpu/cpu$c/cpufreq/cpuinfo_cur_freq 2>/dev/null)"
done

log "== live cpudvfs state =="
for n in cpu0 cpu6 ace scu gic periph; do
	log "$n: sel=$(cat $DF/$n/sel) div=$(cat $DF/$n/div) volt=$(cat $DF/$n/voted_volt) target=$(cat $DF/$n/target)"
done

log "== apcpu dvfs block (0x64018000) =="
log "-- lit map table 0x60-0x88:"
for off in 0x60 0x64 0x68 0x6c 0x70 0x74 0x78 0x7c 0x80 0x84 0x88; do
	rdb 2 $off
done
log "-- big map table 0xa0-0xc4:"
for off in 0xa0 0xa4 0xa8 0xac 0xb0 0xb4 0xb8 0xbc 0xc0 0xc4; do
	rdb 2 $off
done
log "-- work/idle indexes:"
for off in 0x214 0x218 0x224 0x228; do
	rdb 2 $off
done
log "-- per-device live regs 0x30-0x50:"
for off in 0x30 0x34 0x38 0x3c 0x40 0x44 0x48 0x4c 0x50; do
	rdb 2 $off
done

log "== glbregs 0x645a0000 (mpll slots) =="
for off in 0x60 0x64 0x68 0x6c 0x70 0x74 0x78 0x7c 0x80 0x84 0x88 0x8c 0x90 0x94 0x98 0x9c 0xa0 0xa4 0xa8 0xac 0xb0 0xb4 0xb8 0xbc 0xc0 0xc4 0xc8 0xcc 0xd0 0xe8 0xec 0xf0 0xf4 0xf8 0xfc 0x100 0x104 0x108 0x10c 0x110 0x114 0x118; do
	rdb 3 $off
done

log "== glbregs 0x64580000 (mpll-prometheus) =="
for off in 0x60 0x64 0x68 0x6c 0x70 0x74 0x78 0x7c 0x80 0x84 0x88 0x8c 0x90 0x94 0x98 0x9c; do
	rdb 4 $off
done

log "done"
cat $OUT
