def write_font_header(root):
    """Extract the in-tree 8x16 VGA font into a small standalone header.

    CONFIG_FONT_8x16 is off in this build, but lib/fonts/font_8x16.c ships the
    data regardless; parsing it avoids enabling the whole font framework just
    to draw a few hundred characters.
    """
    import re
    src = (root / "lib" / "fonts" / "font_8x16.c").read_bytes().decode("latin-1")
    start = src.index("fontdata_8x16[FONTDATAMAX]")
    body = src[src.index("{", start):]
    # strip comments first: the per-byte comments contain text like
    # "/* 125 0x7d '}' */" which both looks like hex data and closes the body
    # early if we cut at the first '}'.
    body = re.sub(r"/\*.*?\*/", "", body, flags=re.S)
    vals = [int(v, 16) for v in re.findall(r"0x([0-9a-fA-F]{2})", body)]
    if len(vals) < 4096:
        raise SystemExit("font parse produced %d bytes" % len(vals))
    vals = vals[:4096]
    out = ['#ifndef _LINUX_DIAG_FONT_H', '#define _LINUX_DIAG_FONT_H', '',
           '/* 8x16 VGA font, extracted from lib/fonts/font_8x16.c. */',
           'static const unsigned char diag_font_data[4096] __maybe_unused = {']
    for i in range(0, 4096, 16):
        out.append('\t' + ' '.join('0x%02x,' % b for b in vals[i:i + 16]))
    out += ['};', '', '#endif']
    (root / "include" / "linux" / "diag_font.h").write_text('\n'.join(out) + '\n')
    print("wrote include/linux/diag_font.h (4096 font bytes)")


def main():
    panic_stage = sys.argv[1] if len(sys.argv) > 1 else "0"
    arm_stage = sys.argv[2] if len(sys.argv) > 2 else "0"
    smc_stage = sys.argv[3] if len(sys.argv) > 3 else "0"
    paint = sys.argv[4] if len(sys.argv) > 4 else "0"
    screen = sys.argv[5] if len(sys.argv) > 5 else "0"
    src = ROOT / "init" / "main.c"
    hdr = ROOT / "include" / "linux" / "diag_stage.h"

    if screen != "0":
        write_font_header(ROOT)

    hdr.write_text(HEADER.replace("%PANIC%", panic_stage)
                         .replace("%ARM%", arm_stage)
                         .replace("%SMC%", smc_stage)
                         .replace("%PAINT%", paint)
                         .replace("%SCREEN%", screen))
    print("wrote include/linux/diag_stage.h (panic=%s arm=%s smc=%s paint=%s screen=%s)"
          % (panic_stage, arm_stage, smc_stage, paint, screen))

    s = src.read_text()

    if "diag_stage.h" not in s:
        anchor = "asmlinkage __visible void __init start_kernel(void)"
        assert s.count(anchor) == 1
        s = s.replace(anchor, '#include <linux/diag_stage.h>\n\n' + anchor)
        print("added #include <linux/diag_stage.h>")

    # Strip every marker this generator may have inserted in an earlier run
    # (possibly with different anchors), then insert everything fresh.  The
    # branch carries the previous snapshot as a commit, so without this the
    # markers accumulate and end up in dead positions.
    stripped = re.sub(r"[ \t]*DIAG_(?:STAGE_\d+|ARM_HOOK\(\d+\)|SMC_HOOK\(\d+\)|"
                      r"PAINT_HOOK\(\d+\)|STAGE_TAG\(\d+\)|EARLY_HOOK\(\d+\)|"
                      r"INITCALL_NAME\(fn\));\n",
                      "", s)
    if stripped != s:
        print("stripped %d stale DIAG markers from init/main.c"
              % (s.count("DIAG_") - stripped.count("DIAG_")))
        s = stripped

    for anchor, ins, marker in EDITS:
        if marker in s:
            continue
        n = s.count(anchor)
        if n != 1:
            print("WARN: anchor for %s occurs %d times, skipped" % (marker, n))
            continue
        s = s.replace(anchor, anchor + ins)
        print("inserted %s" % marker)

    # Markers that must run before the statement they belong to.
    for anchor, ins, marker in EDITS_BEFORE:
        if marker in s:
            continue
        n = s.count(anchor)
        if n != 1:
            print("WARN: anchor for %s occurs %d times, skipped" % (marker, n))
            continue
        s = s.replace(anchor, ins + anchor)
        print("inserted %s (before anchor)" % marker)

    # Live "which initcall is running" line: do_one_initcall() names the
    # initcall on the permanent header row before calling it, so a hung
    # initcall identifies itself on the panel.
    anchor = "\tif (initcall_blacklisted(fn))\n\t\treturn -EPERM;\n"
    if "DIAG_INITCALL_NAME(fn);" not in s:
        n = s.count(anchor)
        if n != 1:
            print("WARN: do_one_initcall anchor occurs %d times, skipped" % n)
        else:
            s = s.replace(anchor, anchor + "\tDIAG_INITCALL_NAME(fn);\n", 1)
            print("inserted DIAG_INITCALL_NAME(fn) into do_one_initcall")
    # Keep initcall identification independent of the framebuffer.  A single
    # high-priority printk immediately before each call is enough to leave the
    # last attempted initcall in ramoops' circular console buffer, even if the
    # function never returns (and without initcall_debug's doubled chatter).
    call_anchor = "\tDIAG_INITCALL_NAME(fn);\n"
    call_log = "\tpr_emerg(\"DIAG: initcall %pF\\n\", fn);\n"
    if call_log not in s:
        if s.count(call_anchor) == 1:
            s = s.replace(call_anchor, call_anchor + call_log, 1)
            print("inserted ramoops initcall breadcrumb")
        else:
            print("WARN: initcall breadcrumb anchor occurs %d times"
                  % s.count(call_anchor))

    # A tag-27 hang is still before do_initcalls() if it stalls in one of
    # do_basic_setup()'s setup calls. Breadcrumb each call site as well.
    for fn in ("cpuset_init_smp", "shmem_init", "driver_init",
               "init_irq_proc", "do_ctors", "usermodehelper_enable",
               "do_initcalls"):
        anchor = "\t" + fn + "();\n"
        log = "\tpr_emerg(\"DIAG: setup " + fn + "\\n\");\n"
        if log in s:
            continue
        if s.count(anchor) == 1:
            s = s.replace(anchor, log + anchor, 1)
            print("inserted setup breadcrumb: %s" % fn)
        else:
            print("WARN: setup breadcrumb anchor %s occurs %d times"
                  % (fn, s.count(anchor)))

    # The SMC hooks go in separately: main.c already carries the arm hooks
    # from earlier builds, so the EDITS loop above would skip these anchors.
    for n in range(1, 9):
        marker = "DIAG_SMC_HOOK(%d);" % n
        if marker in s:
            continue
        arm = "DIAG_ARM_HOOK(%d);" % n
        if n == 1 and "\tDIAG_STAGE_1;\n" in s:
            anchor = "\tDIAG_STAGE_1;\n"
        elif arm in s:
            anchor = "\t" + arm + "\n"
        else:
            print("WARN: no anchor for %s" % marker)
            continue
        s = s.replace(anchor, anchor + "\t" + marker + "\n", 1)
        print("inserted %s" % marker)

    # Same for the paint hooks (stages 2..8: stage 1 runs before setup_arch()
    # has installed the linear mapping that 0x9e000000 needs).
    for n in range(2, 9):
        marker = "DIAG_PAINT_HOOK(%d);" % n
        if marker in s:
            continue
        smc = "DIAG_SMC_HOOK(%d);" % n
        if smc not in s:
            print("WARN: no smc hook as anchor for %s" % marker)
            continue
        anchor = "\t" + smc + "\n"
        s = s.replace(anchor, anchor + "\t" + marker + "\n", 1)
        print("inserted %s" % marker)

    # Report-only tags for the same stages, so the milestone line covers
    # everything after setup_arch() too (paint bands stop at 19).
    for n in range(2, 9):
        tag = "DIAG_STAGE_TAG(%d);" % (20 + n)
        if tag in s:
            continue
        for cand in ("\tDIAG_PAINT_HOOK(%d);\n" % n,
                     "\tDIAG_SMC_HOOK(%d);\n" % n):
            if cand in s:
                s = s.replace(cand, cand + "\t" + tag + "\n", 1)
                print("inserted %s" % tag)
                break
        else:
            print("WARN: no anchor for %s" % tag)

    # start_kernel()'s statements before setup_arch() (paint mode 2, bands 1..9)
    for anchor, band in EARLY_TRACE:
        hook = "\tDIAG_EARLY_HOOK(%d);\n" % band
        if hook.strip() in s:
            continue
        if s.count(anchor) != 1:
            print("WARN: early anchor occurs %d times: %r"
                  % (s.count(anchor), anchor))
            continue
        s = s.replace(anchor, anchor + hook, 1)
        print("inserted %s" % hook.strip())

    # setup_arch() band 15: the linear mapping now exists, so the on-screen
    # console can start mirroring printk from here on.
    # printk mirrors to the screen (kernel/printk/printk.c)
    pk = ROOT / "kernel" / "printk" / "printk.c"
    p = pk.read_text()
    if screen != "0":
        if "#include <linux/diag_stage.h>" not in p:
            i = p.index("#include <linux/")
            p = p[:i] + "#include <linux/diag_stage.h>\n" + p[i:]
            print("added diag include to printk.c")
        hook = ("\t#if DIAG_SCREEN\n\tdiag_stage_mirror(text, text_len);\n\t#endif\n")
        if "diag_stage_mirror(text, text_len);" not in p:
            # drop a hook from an older generator (it drew into its own,
            # never-initialised copy of the console state)
            p = re.sub(r"[ \t]*#if DIAG_SCREEN\n[ \t]*diag_screen_puts\(text, text_len\);\n[ \t]*#endif\n", "", p)
            anchor = "\treturn log_output(facility, level, lflags,\n"
            if p.count(anchor) == 1:
                p = p.replace(anchor, hook + anchor, 1)
                print("inserted printk->screen hook")
            else:
                print("WARN: printk log_output anchor not unique")
    else:
        p = p.replace("#include <linux/diag_stage.h>\n", "")
        p = re.sub(r"[ \t]*#if DIAG_SCREEN\n[ \t]*diag_(stage_mirror|screen_puts)\(text, text_len\);\n[ \t]*#endif\n", "", p)
    pk.write_text(p)

    # One report per boot for an invalid notifier, instead of a WARN per idle
    # entry.  CONFIG_DEBUG_NOTIFIERS (also set in the shipping config) rejects
    # callbacks that are not in core kernel text; something on the CPU_PM chain
    # is outside it, so the stock WARN fires at every cpuidle exit and buries
    # the real log tail under an identical backtrace.
    nf = ROOT / "kernel" / "notifier.c"
    n = nf.read_text()
    decl = "static bool diag_bad_notifier_reported;\n"
    if decl not in n:
        anchor = "static int notifier_call_chain(struct notifier_block **nl,\n"
        if n.count(anchor) == 1:
            n = n.replace(anchor,
                          "#include <linux/printk.h>\n" + decl + "\n" + anchor, 1)
            print("added diag_bad_notifier_reported to notifier.c")
        else:
            print("WARN: notifier.c has no notifier_call_chain anchor")
    if "diag: invalid notifier" not in n:
        warn = ("#ifdef CONFIG_DEBUG_NOTIFIERS\n"
                "\t\tif (unlikely(!func_ptr_is_kernel_text(nb->notifier_call))) {\n"
                "\t\t\tWARN(1, \"Invalid notifier called!\");\n"
                "\t\t\tnb = next_nb;\n"
                "\t\t\tcontinue;\n"
                "\t\t}\n"
                "#endif\n")
        repl = ("#ifdef CONFIG_DEBUG_NOTIFIERS\n"
                "\t\tif (unlikely(!func_ptr_is_kernel_text(nb->notifier_call))) {\n"
                "\t\t\t/*\n"
                "\t\t\t * DIAG: report once, naming the block and its callback,\n"
                "\t\t\t * then keep skipping it.  On this device this is the\n"
                "\t\t\t * CPU_PM chain, so the stock WARN fires at every\n"
                "\t\t\t * cpuidle exit and buries the log tail.\n"
                "\t\t\t */\n"
                "\t\t\tif (!diag_bad_notifier_reported) {\n"
                "\t\t\t\tdiag_bad_notifier_reported = true;\n"
                "\t\t\t\tpr_err(\"diag: invalid notifier %px callback=%pS (skipped)\\n\",\n"
                "\t\t\t\t       nb, nb->notifier_call);\n"
                "\t\t\t}\n"
                "\t\t\tnb = next_nb;\n"
                "\t\t\tcontinue;\n"
                "\t\t}\n"
                "#endif\n")
        if n.count(warn) != 1:
            print("WARN: notifier.c anchor found %d times" % n.count(warn))
        else:
            n = n.replace(warn, repl, 1)
            print("patched notifier.c: one-time invalid-notifier report")
    nf.write_text(n)

    # setup_arch() trace (paint mode 2): milestones inside
    # arch/arm64/kernel/setup.c, bands 1..9.  The first ones must use
    # early_ioremap() because the linear mapping of 0x9e000000 only appears
    # with paging_init(); the later ones use phys_to_virt().
    setup = ROOT / "arch" / "arm64" / "kernel" / "setup.c"
    t = setup.read_text()
    # Drop any trace hooks from an earlier run so the band numbering is never
    # a mix of two generations (they are re-inserted below under the current
    # numbering).
    stripped = re.sub(r"[ \t]*DIAG_TRACE_HOOK\([0-9]+, [01]\);\n", "", t)
    if stripped != t:
        print("removed stale DIAG_TRACE_HOOK lines from setup.c")
        t = stripped
    if "diag_stage.h" not in t:
        inc = "#include <linux/init.h>\n"
        if t.count(inc) == 1:
            t = t.replace(inc, inc + "#include <linux/diag_stage.h>\n", 1)
            print("added #include <linux/diag_stage.h> to setup.c")
        else:
            print("WARN: include anchor missing in setup.c")
    # The printk mirror must land in this file's copy of the console state;
    # see the long comment on diag_stage_mirror() in the header.
    old_mirror = (
        "#if DIAG_SCREEN\n"
        "/* the one copy of the panel console that printk mirrors into */\n"
        "void diag_stage_mirror(const char *text, size_t len)\n"
        "{\n"
        "\tdiag_screen_puts(text, len);\n"
        "}\n"
        "#endif\n")
    if old_mirror in t:
        # a previous run inserted the wrapper without the shared instance
        t = t.replace(old_mirror, "", 1)
    mirror_def = (
        "#if DIAG_SCREEN\n"
        "/* the single console instance shared by every translation unit */\n"
        "struct diag_console diag_state;\n"
        "\n"
        "void diag_stage_mirror(const char *text, size_t len)\n"
        "{\n"
        "\tdiag_screen_puts(text, len);\n"
        "}\n"
        "#endif\n")
    if "void diag_stage_mirror" not in t:
        inc = "#include <linux/diag_stage.h>\n"
        if t.count(inc) == 1:
            t = t.replace(inc, inc + "\n" + mirror_def, 1)
            print("added diag_stage_mirror() to setup.c")
        else:
            print("WARN: no diag include anchor for diag_stage_mirror()")
    for anchor, hook in SETUP_TRACE:
        if hook.strip() in t:
            continue
        if t.count(anchor) != 1:
            print("WARN: anchor occurs %d times in setup.c: %r"
                  % (t.count(anchor), anchor))
            continue
        t = t.replace(anchor, anchor + hook, 1)
        print("inserted %s in setup.c" % hook.strip())
    # band 10: the first statement of setup_arch() itself
    entry = "void __init setup_arch(char **cmdline_p)\n{\n"
    hook10 = "\tDIAG_EARLY_HOOK(10);\n"
    if hook10.strip() not in t and t.count(entry) == 1:
        t = t.replace(entry, entry + hook10, 1)
        print("inserted %s in setup.c" % hook10.strip())
    # the on-screen console can start once the linear map exists
    screen_init = "\tDIAG_SCREEN_INIT;\n"
    el_report = ("\t/* KVM needs the kernel to have been entered at EL2: record\n"
                 "\t * what the bootloader actually handed over, while we can\n"
                 "\t * still draw text on the panel.\n"
                 "\t */\n"
                 "\tDIAG_EL_REPORT;\n")
    paging = "\tpaging_init();\n"
    if screen_init.strip() not in t and t.count(paging) == 1:
        t = t.replace(paging, paging + screen_init, 1)
        print("inserted %s in setup.c" % screen_init.strip())
    if el_report.strip() not in t:
        if screen_init in t:
            t = t.replace(screen_init, screen_init + el_report, 1)
            print("inserted DIAG_EL_REPORT in setup.c")
        else:
            print("WARN: no DIAG_SCREEN_INIT anchor for DIAG_EL_REPORT")
    setup.write_text(t)

    # the end-of-init panic must not mask any instrument
    old = "#if defined(DIAG_PANIC_AFTER_INIT) && DIAG_PANIC_STAGE == 0"
    new = ("#if defined(DIAG_PANIC_AFTER_INIT) && DIAG_PANIC_STAGE == 0 && "
           "DIAG_ARM_STAGE == 0 && DIAG_SMC_STAGE == 0 && DIAG_PAINT == 0")
    if old in s and new not in s:
        s = s.replace(old, new)
        print("made DIAG_PANIC_AFTER_INIT yield to staged panics and to the arm")

    src.write_text(s)


if __name__ == "__main__":
    main()
