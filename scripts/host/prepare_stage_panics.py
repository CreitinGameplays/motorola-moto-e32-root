#!/usr/bin/env python3
"""Prepare the staged instrumentation in init/main.c (idempotent).

Two independent knobs, both in the generated include/linux/diag_stage.h, so a
bisection step is one incremental rebuild of init/main.c (seconds), not a full
kernel build:

  DIAG_PANIC_STAGE  N   panic() at stage N.  Useful only for stages 8+ and for
                        anything after do_basic_setup, because the PSCI restart
                        handler is installed by an arch_initcall - before that
                        a panic cannot reset the board and looks like a hang.
  DIAG_ARM_STAGE    N   arm the AON watchdog (10 s, reset only, no FIQ) at
                        stage N and keep booting.  N=9 arms at every stage
                        from 2 upwards.  0 = off.
  DIAG_SMC_STAGE    N   reset the SoC through PSCI SYSTEM_RESET (SMCCC
                        0x84000009) at stage N.  Unlike the AON watchdog this
                        needs no MMIO mapping and no clock, so it works from
                        the first instruction of start_kernel(); it is a
                        warm reset, so pstore survives it.  If the SMC is not
                        implemented the call returns and the boot continues.
                        0 = off.
"""
import pathlib
import re
import sys

ROOT = pathlib.Path.home() / "kernel-sprd"

HEADER = """#ifndef _LINUX_DIAG_STAGE_H
#define _LINUX_DIAG_STAGE_H
/*
 * DIAG ONLY - not part of a real build.
 * Generated by scripts/host/prepare_stage_panics.py, do not edit by hand.
 *
 *   1  first statement of start_kernel()   (proves the Image is executing)
 *   2  after setup_arch()                  (DTB, memory map, paging, PSCI fw)
 *   3  after build_all_zonelists/page_alloc
 *   4  after check_bugs()
 *   5  just before rest_init()
 *   6  first statement of kernel_init()
 *   7  after do_pre_smp_initcalls()
 *   8  after do_basic_setup()              (every initcall, all drivers)
 */

#include <linux/io.h>
#include <linux/bitops.h>
#include <linux/arm-smccc.h>
#include <linux/mm.h>
#include <asm/barrier.h>
#include <asm/early_ioremap.h>

#define DIAG_PANIC_STAGE %PANIC%
#define DIAG_ARM_STAGE %ARM%
#define DIAG_ARM_TIMEOUT 10
#define DIAG_SMC_STAGE %SMC%

/*
 * Reset the SoC through the PSCI SYSTEM_RESET function (SMCCC 0x84000009).
 *
 * This is the only reset source usable at the very first statement of
 * start_kernel(): it is a secure-monitor call, so it needs no device mapping,
 * no clock and no driver.  It is also a warm reset, which is what makes the
 * ramoops/pstore region survive and be readable on the next boot.
 *
 * If the monitor does not implement the function the call simply returns and
 * the boot continues, so "no reset" must be read as "the code did not run"
 * only after a stage that is known to be reached.
 */
static inline void diag_psci_reset(void)
{
\tstruct arm_smccc_res res;

\tarm_smccc_smc(0x84000009UL, 0, 0, 0, 0, 0, 0, 0, &res);
}

#define DIAG_SMC_HOOK(n) \\
\tdo { if (DIAG_SMC_STAGE == (n)) diag_psci_reset(); } while (0)

#define DIAG_PAINT %PAINT%

/*
 * Visual stage trace: paint white bands at the bootloader's framebuffer.
 *
 * The bootloader leaves the panel scanning out of lcd_base=0x9e000000, and
 * that picture stays up while a half-booted kernel hangs (the operator sees
 * the Motorola logo).  Filling horizontal bands there therefore gives a
 * progress bar that needs no reset, no ramoops and no console.
 *
 * Layout: band n occupies bytes [n*DIAG_PAINT_BAND, (n+1)*DIAG_PAINT_BAND) of
 * physical 0x9e000000, so the bands stack downwards and their number is the
 * answer.  10 bands are 1.28 MB, comfortably inside the 1600x720x32 panel
 * buffer and below the next reserved region at 0x9f000000.
 *
 * band 0 is painted by the entry stub (scripts/host/entry_paint.py, MMU off,
 * before head.S).  DIAG_PAINT=1 paints start_kernel()'s stages 2..8 into
 * bands 1..7; DIAG_PAINT=2 paints the setup_arch() milestones below into
 * bands 1..9.  Two paint paths, because the linear mapping is only complete
 * after paging_init():
 *   diag_paint_early()  early_ioremap(), usable from early_ioremap_init()
 *                       until early_ioremap_reset() inside setup_arch();
 *   diag_paint()        phys_to_virt(), valid once paging_init() has mapped
 *                       the reserved-memory node (it has no `no-map`).
 */
#define DIAG_PAINT_BASE 0x9e000000UL
#define DIAG_PAINT_BAND 0x20000UL\t/* 131072 bytes = 128 KB */

static inline void diag_paint(unsigned int band)
{
\tvolatile u64 *p = (volatile u64 *)phys_to_virt(DIAG_PAINT_BASE +
\t\t\t\t\t      band * DIAG_PAINT_BAND);
\tunsigned int i;

\tfor (i = 0; i < DIAG_PAINT_BAND / sizeof(u64); i++)
\t\tp[i] = ~0ULL;
\tdsb(sy);
}

static inline void diag_paint_early(unsigned int band)
{
\tvoid __iomem *p = early_ioremap(DIAG_PAINT_BASE + band * DIAG_PAINT_BAND,
\t\t\t\t\tDIAG_PAINT_BAND);

\tif (!p)
\t\treturn;
\tmemset_io(p, 0xff, DIAG_PAINT_BAND);
\tearly_iounmap(p, DIAG_PAINT_BAND);
\tdsb(sy);
}

/* start_kernel() stages (mode 1) */
#define DIAG_PAINT_HOOK(n) \\
\tdo { if (DIAG_PAINT == 1) diag_paint((n) - 1); } while (0)

/* setup_arch() milestones (mode 2); e = 1 for the early_ioremap path */
#define DIAG_TRACE_HOOK(n, e) \\
\tdo { if (DIAG_PAINT == 2) \\
\t\tif (e) diag_paint_early(n); else diag_paint(n); } while (0)

/*
 * Arm the SoC's AON watchdog directly.  This is deliberately independent of
 * the driver: drivers/watchdog/sprd_wdt_fiq.c registers with
 * module_platform_driver(), i.e. a device_initcall, which is far too late to
 * cover a stall in start_kernel()/setup_arch().  The register sequence is
 * copied from sprd_wdt_fiq_{unlock,load_value,enable,start}(); interrupts are
 * left off (INT_EN clear) so a timeout is a plain SoC reset, no FIQ needed.
 *
 * 0x644e0000 = /soc/aon/watchdog@644e0000 (sprd,wdt-r2p0-fiq).
 */
static inline void diag_arm_aon_wdt(void)
{
\tvoid __iomem *base = ioremap(0x644e0000, 0x1000);
\tu32 step = DIAG_ARM_TIMEOUT * 32768U;
\tint i;

\tif (!base)
\t\treturn;

\twritel_relaxed(0xe551, base + 0x20);       /* LOCK: unlock key */
\twritel_relaxed((step >> 16) & 0xffff, base + 0x04); /* LOAD_HIGH */
\twritel_relaxed(step & 0xffff, base + 0x00);         /* LOAD_LOW */
\twritel_relaxed(0, base + 0x30);            /* IRQ_LOAD_HIGH */
\twritel_relaxed(0, base + 0x2c);            /* IRQ_LOAD_LOW */
\twritel_relaxed(0, base + 0x20);            /* LOCK: lock again */

\t/* wait for LD_BUSY to clear, as the driver does */
\tfor (i = 0; i < 1000; i++) {
\t\tif (!(readl_relaxed(base + 0x10) & BIT(4)))
\t\t\tbreak;
\t\tcpu_relax();
\t}

\t/* CTRL: NEW_VER_EN, then CNT_EN | RST_EN (no INT_EN) */
\twritel_relaxed(readl_relaxed(base + 0x08) | BIT(2), base + 0x08);
\twritel_relaxed(readl_relaxed(base + 0x08) | BIT(1) | BIT(3), base + 0x08);
}

#define DIAG_ARM_HOOK(n) \\
\tdo { if (DIAG_ARM_STAGE == (n) || DIAG_ARM_STAGE == 9) diag_arm_aon_wdt(); } while (0)
"""

for n in range(1, 9):
    HEADER += """
#if DIAG_PANIC_STAGE == %d
#define DIAG_STAGE_%d panic("DIAG: stage %d reached")
#else
#define DIAG_STAGE_%d do { } while (0)
#endif
""" % (n, n, n, n)

HEADER += "\n#endif /* _LINUX_DIAG_STAGE_H */\n"

EDITS = [
    ("asmlinkage __visible void __init start_kernel(void)\n{\n\tchar *command_line;\n\tchar *after_dashes;\n",
     "\tDIAG_STAGE_1;\n", "DIAG_STAGE_1;"),
    ("\tpr_notice(\"%s\", linux_banner);\n\tsetup_arch(&command_line);\n",
     "\tDIAG_STAGE_2;\n\tDIAG_ARM_HOOK(2);\n", "DIAG_ARM_HOOK(2);"),
    ("\tbuild_all_zonelists(NULL);\n\tpage_alloc_init();\n",
     "\tDIAG_STAGE_3;\n\tDIAG_ARM_HOOK(3);\n", "DIAG_ARM_HOOK(3);"),
    ("\tcheck_bugs();\n",
     "\tDIAG_STAGE_4;\n\tDIAG_ARM_HOOK(4);\n", "DIAG_ARM_HOOK(4);"),
    ("\t/* Do the rest non-__init'ed, we're now alive */\n\trest_init();\n",
     "\tDIAG_STAGE_5;\n\tDIAG_ARM_HOOK(5);\n", "DIAG_ARM_HOOK(5);"),
    ("static int __ref kernel_init(void *unused)\n{\n\tint ret;\n\n\tkernel_init_freeable();\n",
     "\tDIAG_STAGE_6;\n\tDIAG_ARM_HOOK(6);\n", "DIAG_ARM_HOOK(6);"),
    ("\tdo_pre_smp_initcalls();\n\tlockup_detector_init();\n",
     "\tDIAG_STAGE_7;\n\tDIAG_ARM_HOOK(7);\n", "DIAG_ARM_HOOK(7);"),
    ("\tdo_basic_setup();\n",
     "\tDIAG_STAGE_8;\n\tDIAG_ARM_HOOK(8);\n", "DIAG_ARM_HOOK(8);"),
]

# setup_arch() milestones for paint mode 2, in execution order.  Bands 1..4
# use early_ioremap() (before paging_init()), bands 5..9 phys_to_virt().
SETUP_TRACE = [
    ("\tearly_ioremap_init();\n", "\tDIAG_TRACE_HOOK(1, 1);\n"),
    ("\tsetup_machine_fdt(__fdt_pointer);\n", "\tDIAG_TRACE_HOOK(2, 1);\n"),
    ("\tparse_early_param();\n", "\tDIAG_TRACE_HOOK(3, 1);\n"),
    ("\tarm64_memblock_init();\n", "\tDIAG_TRACE_HOOK(4, 1);\n"),
    ("\tpaging_init();\n", "\tDIAG_TRACE_HOOK(5, 0);\n"),
    ("\t\tunflatten_device_tree();\n", "\t\tDIAG_TRACE_HOOK(6, 0);\n"),
    ("\trequest_standard_resources();\n", "\tDIAG_TRACE_HOOK(7, 0);\n"),
    ("\tsmp_init_cpus();\n", "\tDIAG_TRACE_HOOK(8, 0);\n"),
    ("\tsmp_build_mpidr_hash();\n", "\tDIAG_TRACE_HOOK(9, 0);\n"),
]


def main():
    panic_stage = sys.argv[1] if len(sys.argv) > 1 else "0"
    arm_stage = sys.argv[2] if len(sys.argv) > 2 else "0"
    smc_stage = sys.argv[3] if len(sys.argv) > 3 else "0"
    paint = sys.argv[4] if len(sys.argv) > 4 else "0"
    src = ROOT / "init" / "main.c"
    hdr = ROOT / "include" / "linux" / "diag_stage.h"

    hdr.write_text(HEADER.replace("%PANIC%", panic_stage)
                         .replace("%ARM%", arm_stage)
                         .replace("%SMC%", smc_stage)
                         .replace("%PAINT%", paint))
    print("wrote include/linux/diag_stage.h (panic=%s arm=%s smc=%s paint=%s, %ds)"
          % (panic_stage, arm_stage, smc_stage, paint, 10))

    s = src.read_text()

    if "diag_stage.h" not in s:
        anchor = "asmlinkage __visible void __init start_kernel(void)"
        assert s.count(anchor) == 1
        s = s.replace(anchor, '#include <linux/diag_stage.h>\n\n' + anchor)
        print("added #include <linux/diag_stage.h>")

    for anchor, ins, marker in EDITS:
        if marker in s:
            continue
        n = s.count(anchor)
        if n != 1:
            print("WARN: anchor for %s occurs %d times, skipped" % (marker, n))
            continue
        s = s.replace(anchor, anchor + ins)
        print("inserted %s" % marker)

    # The SMC hooks go in separately: main.c already carries the arm hooks
    # from earlier builds, so the EDITS loop above would skip these anchors.
    for n in range(1, 9):
        marker = "DIAG_SMC_HOOK(%d);" % n
        if marker in s:
            continue
        arm = "DIAG_ARM_HOOK(%d);" % n
        if n == 1 and "\tDIAG_STAGE_1;\n" in s:
            anchor = "\tDIAG_STAGE_1;\n"
        elif arm in s:
            anchor = "\t" + arm + "\n"
        else:
            print("WARN: no anchor for %s" % marker)
            continue
        s = s.replace(anchor, anchor + "\t" + marker + "\n", 1)
        print("inserted %s" % marker)

    # Same for the paint hooks (stages 2..8: stage 1 runs before setup_arch()
    # has installed the linear mapping that 0x9e000000 needs).
    for n in range(2, 9):
        marker = "DIAG_PAINT_HOOK(%d);" % n
        if marker in s:
            continue
        smc = "DIAG_SMC_HOOK(%d);" % n
        if smc not in s:
            print("WARN: no smc hook as anchor for %s" % marker)
            continue
        anchor = "\t" + smc + "\n"
        s = s.replace(anchor, anchor + "\t" + marker + "\n", 1)
        print("inserted %s" % marker)

    # setup_arch() trace (paint mode 2): milestones inside
    # arch/arm64/kernel/setup.c, bands 1..9.  The first ones must use
    # early_ioremap() because the linear mapping of 0x9e000000 only appears
    # with paging_init(); the later ones use phys_to_virt().
    setup = ROOT / "arch" / "arm64" / "kernel" / "setup.c"
    t = setup.read_text()
    if "diag_stage.h" not in t:
        inc = "#include <linux/init.h>\n"
        if t.count(inc) == 1:
            t = t.replace(inc, inc + "#include <linux/diag_stage.h>\n", 1)
            print("added #include <linux/diag_stage.h> to setup.c")
        else:
            print("WARN: include anchor missing in setup.c")
    for anchor, hook in SETUP_TRACE:
        if hook.strip() in t:
            continue
        if t.count(anchor) != 1:
            print("WARN: anchor occurs %d times in setup.c: %r"
                  % (t.count(anchor), anchor))
            continue
        t = t.replace(anchor, anchor + hook, 1)
        print("inserted %s in setup.c" % hook.strip())
    setup.write_text(t)

    # the end-of-init panic must not mask any instrument
    old = "#if defined(DIAG_PANIC_AFTER_INIT) && DIAG_PANIC_STAGE == 0"
    new = ("#if defined(DIAG_PANIC_AFTER_INIT) && DIAG_PANIC_STAGE == 0 && "
           "DIAG_ARM_STAGE == 0 && DIAG_SMC_STAGE == 0 && DIAG_PAINT == 0")
    if old in s and new not in s:
        s = s.replace(old, new)
        print("made DIAG_PANIC_AFTER_INIT yield to staged panics and to the arm")

    src.write_text(s)


if __name__ == "__main__":
    main()